TestResult VulkanEngine::runTriangleTest(int frameCount) {
    LOGI("Running Vulkan Triangle Test...");

    // 创建着色器模块
    VkShaderModule vertModule = createShaderModule(triangleVertSpv, sizeof(triangleVertSpv));
    VkShaderModule fragModule = createShaderModule(triangleFragSpv, sizeof(triangleFragSpv));

    if (vertModule == VK_NULL_HANDLE || fragModule == VK_NULL_HANDLE) {
        LOGE("Failed to create shader modules");
        return {};
    }

    // 由于着色器是硬编码的 SPIR-V，这里简化实现
    // 实际项目中应该使用 glslangValidator 编译 GLSL 到 SPIR-V

    // 清理
    vkDestroyShaderModule(device_->getDevice(), vertModule, nullptr);
    vkDestroyShaderModule(device_->getDevice(), fragModule, nullptr);

    // 返回占位结果
    TestResult result;
    result.name = "Triangle Rendering";
    result.api = getApiName();
    result.fps = 0.0f;
    result.frameTimeMs = 0.0f;
    result.triangles = 0;
    result.drawCalls = 0;
    return result;
}

